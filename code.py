# arithmetic
a = 4
b = 5
print("arithmetic")
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a**b)
print(a%b)

# relational 
print("relational")
print(a==b)
print(a>b)
print(4<6)

# assignment
print("assignment")
print(a)
a = b
print(a)
a += 1
print(a)

# logical - not, and, or 
print("logical")
var = False
print(not var)
print(not (5 > 4))
print((5>3) and (3>8))
print((5>3) or (3>8))